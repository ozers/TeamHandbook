import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { opencodeConfigDir } from "./opencode.js";

/**
 * The commands that work under OpenCode today. Listing, drafting and reviewing read git and
 * the local queue and nothing else; `learn` needs the session the hooks capture, and init,
 * join, share and leave deliver through a Claude Code plugin marketplace, which OpenCode has
 * no counterpart for. Installing those would hand the user a command that fails halfway.
 */
export const OPENCODE_COMMANDS = ["mine", "review", "status", "doctor", "demo"] as const;

/**
 * The first line of every file this writes. It is how a later install or a removal tells a
 * file it owns from one the user put in the same directory, which it never overwrites.
 */
export const GENERATED_MARK = "<!-- generated by TeamHandbook for OpenCode: edits are replaced on reinstall -->";

/** OpenCode names a command by its path under commands/, so these become /handbook/mine and so on. */
export const OPENCODE_COMMAND_DIR = "handbook";

/**
 * Turn one Claude Code command file into its OpenCode counterpart.
 *
 * The body stays the same instructions, so the routing suite's measured wording is not
 * forked into a second copy that drifts; only what names Claude Code's machinery changes.
 * `commands/*.md` stays the one source.
 *
 * OpenCode expands a template before the model sees it: `$1`..`$N` and `$ARGUMENTS` are
 * substituted, then every `` !`...` `` in the result is run in a shell (session/prompt.ts).
 * A source file holding either would run or rewrite text nobody meant as a command, so it is
 * refused rather than escaped: an escape that OpenCode's next release reads differently is a
 * shell command in a file the user trusted.
 */
export function toOpencodeCommand(source: string, pluginRoot: string): string {
  if (/[`"$\\\n]/.test(pluginRoot)) {
    throw new Error(`plugin path ${JSON.stringify(pluginRoot)} holds a character a shell line cannot quote safely`);
  }
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(source.replace(/\r\n?/g, "\n"));
  if (!match) throw new Error("command file has no frontmatter");
  const description = /^description:\s*(.*)$/m
    .exec(match[1]!)?.[1]
    ?.trim()
    .replaceAll("/handbook:", `/${OPENCODE_COMMAND_DIR}/`);
  if (!description) throw new Error("command file has no description");
  let body = match[2]!;
  if (body.includes("!`")) throw new Error("command body holds !` which OpenCode would run as a shell command");
  if (/\$\d/.test(body)) throw new Error("command body holds $<digit> which OpenCode would replace with an argument");
  // Every CLI call carries the host, because the engine picks which model CLI to call from it
  // and one machine can run both hosts.
  body = body.replaceAll('node "${CLAUDE_PLUGIN_ROOT}/', `TEAMHANDBOOK_HOST=opencode node "${pluginRoot}/`);
  body = body.replaceAll("${CLAUDE_PLUGIN_ROOT}", pluginRoot);
  // OpenCode's multiple-choice tool is `question`; the TUI's build agent allows it
  body = body.replaceAll("AskUserQuestion", "`question` tool");
  body = body.replaceAll("/handbook:", `/${OPENCODE_COMMAND_DIR}/`);
  body = body.replaceAll("the user's own `claude` CLI", "the user's own `opencode` CLI");
  // Only `description` is carried: argument-hint and the rest are Claude Code's, and an
  // unknown key is one schema change from a command OpenCode refuses to load.
  return `---\ndescription: ${description}\n---\n${GENERATED_MARK}\n${COMMAND_NAME_NOTE}\n${body}`;
}

/**
 * TeamHandbook's own output names its commands the Claude Code way. Rewriting every message
 * the CLI prints for one host is a larger change than this needs; telling the model once is
 * enough for it to relay the right name.
 */
export const COMMAND_NAME_NOTE =
  `TeamHandbook's output names its commands as /handbook:<name>; in OpenCode the same command is /${OPENCODE_COMMAND_DIR}/<name>, so relay that form.\n`;

export interface InstallResult {
  dir: string;
  written: string[];
  /** files in the directory this did not write and so left alone */
  skipped: string[];
}

/** Where the commands go: the user's OpenCode config, or one project's `.opencode`. */
export function opencodeCommandsDir(target: { project?: string; env?: NodeJS.ProcessEnv } = {}): string {
  const base = target.project ? join(target.project, ".opencode") : opencodeConfigDir(target.env);
  return join(base, "commands", OPENCODE_COMMAND_DIR);
}

function ownedByUs(file: string): boolean {
  try {
    return readFileSync(file, "utf8").split("\n").includes(GENERATED_MARK);
  } catch {
    return false;
  }
}

export function installOpencodeCommands(pluginRoot: string, dir: string): InstallResult {
  // Every file is converted before any is written, so a refused source leaves the previous
  // install whole instead of half replaced.
  const converted = OPENCODE_COMMANDS.map((name) => ({
    name,
    text: toOpencodeCommand(readFileSync(join(pluginRoot, "commands", `${name}.md`), "utf8"), pluginRoot),
  }));
  mkdirSync(dir, { recursive: true });
  const result: InstallResult = { dir, written: [], skipped: [] };
  for (const { name, text } of converted) {
    const file = join(dir, `${name}.md`);
    if (existsSync(file) && !ownedByUs(file)) {
      result.skipped.push(`${name}.md`);
      continue;
    }
    writeFileSync(file, text);
    result.written.push(`${name}.md`);
  }
  return result;
}

/** Removes only the files this wrote; the directory goes too once nothing else is in it. */
export function removeOpencodeCommands(dir: string): string[] {
  if (!existsSync(dir)) return [];
  const removed: string[] = [];
  for (const name of readdirSync(dir)) {
    const file = join(dir, name);
    if (name.endsWith(".md") && ownedByUs(file)) {
      rmSync(file);
      removed.push(name);
    }
  }
  if (readdirSync(dir).length === 0) rmSync(dir, { recursive: true });
  return removed;
}
